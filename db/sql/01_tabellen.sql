-- -----------------------------------------------------------------------------------------------------
CREATE TABLE BR_SCHEMA (
  VERSION      NUMBER(4) NOT NULL,
  EINGERICHTET TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  APP_VERSION  VARCHAR2(20 CHAR) NOT NULL,
  TEXT         VARCHAR2(400 CHAR),
  CONSTRAINT BR_SCHEMA_PK PRIMARY KEY (VERSION)
);

-- -----------------------------------------------------------------------------------------------------
-- BR_QUELLE: Quellen zum Vorbild (Werkbuch Abschnitt 14), Daten (GLO-30, DGM200, DGM1, ALKIS, DWD, HSB) und eigene Messungen.
-- -----------------------------------------------------------------------------------------------------
CREATE SEQUENCE BR_QUELLE_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE BR_QUELLE (
  ID        NUMBER(10) NOT NULL,
  KURZ      VARCHAR2(30 CHAR) NOT NULL,
  TITEL     VARCHAR2(300 CHAR) NOT NULL,
  URL       VARCHAR2(400 CHAR),
  ART       VARCHAR2(8) NOT NULL,
  ABGERUFEN DATE,
  BEMERKUNG VARCHAR2(400 CHAR),
  HERKUNFT  VARCHAR2(12) DEFAULT 'EIGEN' NOT NULL,
  ANGELEGT  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  GEAENDERT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT BR_QUELLE_PK PRIMARY KEY (ID),
  CONSTRAINT BR_QUELLE_UK UNIQUE (KURZ),
  CONSTRAINT BR_QUELLE_ART_CK CHECK (ART IN ('WEB','BUCH','ARTIKEL','DATEN','MESSUNG')),
  CONSTRAINT BR_QUELLE_HERKUNFT_CK CHECK (HERKUNFT IN ('MITGELIEFERT','EIGEN'))
);

CREATE OR REPLACE TRIGGER BR_QUELLE_BIU
BEFORE INSERT OR UPDATE ON BR_QUELLE
FOR EACH ROW
BEGIN
  IF INSERTING THEN
    IF :NEW.ID IS NULL THEN
      :NEW.ID := BR_QUELLE_SEQ.NEXTVAL;
    END IF;
    :NEW.ANGELEGT := NVL(:NEW.ANGELEGT, SYSTIMESTAMP);
  END IF;
  :NEW.GEAENDERT := SYSTIMESTAMP;
END;
/

