--
-- Wiederholbar: Was schon da ist, meldet Oracle mit ORA-00955 (Name schon vergeben); der Einrichter der App
-- übergeht genau diese Meldung. In SQL Developer als Skript ausführen (F5); die Meldungen bei einem zweiten
-- Lauf sind dann harmlos. Dieses Skript löscht nichts.
--
-- Hauskonvention: ID aus Sequence + Trigger, nie GENERATED AS IDENTITY. Je Spalte eine Zeile, damit der
-- Einrichter fehlende Spalten erkennen und nachtragen kann. Lage in 8307 (Länge, Breite, F28 A), daneben
-- Szenenmeter X_M, Z_M (x nach Osten, z nach Süden, Ursprung am Gipfelstein: UTM 32N E 611 400, N 5 739 940).
-- Szenenzeit: SZENE_MS = Millisekunden seit 1970 (UTC), SZENE_TEXT so, wie die App sie zeigt
-- („21.10.2026 07:52 MESZ“), SZENE_TAG = 'JJJJ-MM-TT' für Filter, in BR_STUNDE dazu SZENENZEIT als
-- TIMESTAMP WITH TIME ZONE (Europe/Berlin).
-- 39 Tabellen in neun Themen: Betrieb, Quellen, Gelände, Boden und Fels, Wind und Klima, Bahn, Gipfel, Chronik,
-- Regie, Kamera, Eigenes und Packages.
-- =====================================================================================================


-- -----------------------------------------------------------------------------------------------------
